//协议数据单元
struct PDU{
    uint uiTotalLen;    //总长度
    uint uiMsgLen;      //柔性数组长度
    uint uiType;        //消息类型
    char caData[64];    //参数
    char caMsg[];       //实际消息（柔性数组）
};

//文件信息结构体
struct FileInfo{
    char caName[32];    //文件名
    int iFileType;      //类型
};


PDU *mkPDU(uint uiMsLen = 0);

